// ShikshaGap Service Worker: App-Shell & Offline Engine
// Version: v1.4-shell
const CACHE_NAME = 'shikshagap-shell-v1.4';
const SHELL_ASSETS = [
  '/',
  '/manifest.json',
  '/icon.svg',
  '/offline.html',
  '/licenses',
  '/privacy',
  '/terms',
  '/cookies'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(SHELL_ASSETS);
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) {
            return caches.delete(key);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);

  // SECURITY: Strictly ignore and never cache API calls or authenticated routes
  if (url.pathname.startsWith('/api/') || url.pathname.startsWith('/app')) {
    return; // Pass through to network directly
  }

  // Non-GET requests should never be cached
  if (request.method !== 'GET') {
    return;
  }

  // HTML navigation: NETWORK-FIRST to ensure fresh deploys are seen immediately
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response && response.status === 200) {
            const responseClone = response.clone();
            caches.open(CACHE_NAME).then((cache) => {
              cache.put(request, responseClone);
            });
          }
          return response;
        })
        .catch(() => {
          return caches.match(request).then((cached) => {
            return cached || caches.match('/offline.html');
          });
        })
    );
    return;
  }

  // Static assets: Cache-first with network fallback
  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;

      return fetch(request).then((response) => {
        if (response && response.status === 200) {
          const responseClone = response.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(request, responseClone);
          });
        }
        return response;
      });
    })
  );
});
